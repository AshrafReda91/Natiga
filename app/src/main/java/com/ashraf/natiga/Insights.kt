package com.ashraf.natiga

// تأملات الشهور القبطية — من لوحة «السنة القبطية: دورة الحياة في انسجام مع الطبيعة»
// (لقاء الروح — محمد فاروق المليجي)

data class Insight(
    val proverb: String,  // المثل الشعبي
    val theme: String,    // معنى الشهر
    val advice: String    // التوجيه
)

data class Season(val name: String, val meaning: String)

object Insights {
    // بالترتيب: توت (٠) … مسرى (١١)، النسيء (١٢)
    private val MONTHS = arrayOf(
        Insight(
            "«توت يقول للحر موت»", "التجدد والبداية",
            "اترك القديم ينتهي. نظّف مساحتك، وجدّد نيتك للدورة الجديدة."
        ),
        Insight(
            "«بابه خُش واقفل البوابة»", "الدخول إلى الداخل",
            "أغلق الأبواب التي تشتت طاقتك. ضع حدوداً، وأعد انتباهك إلى عالمك الداخلي."
        ),
        Insight(
            "«هاتور أبو الذهب المنثور»", "الاستقبال والوفرة",
            "انظر إلى ما هو موجود بالفعل. اسمح لنفسك بالاستقبال، والامتنان، والاستمتاع."
        ),
        Insight(
            "«كيهك صباحك مساك، تقوم من فطورك تحضر عشاك»", "السكون والنور الداخلي",
            "وقت للتأمل، والإنصات، والأحلام، قبل الاندفاع نحو الفعل."
        ),
        Insight(
            "«طوبه يخلي الصبية كركوبة»", "حفظ الطاقة",
            "الانكماش ليس فشلاً. احمِ مواردك، استرح، وغذِّ جسدك وروحك."
        ),
        Insight(
            "«أمشير أبو الزعابيب الكتير»", "التطهير والتحريك",
            "اسمح للحياة أن تحرّك ما جمد. تخلَّ عمّا انتهى، ولا تقاوم كل عاصفة."
        ),
        Insight(
            "«برمهات روح الغيط وهات»", "الزرع والفعل",
            "ما تأملته يحتاج الآن إلى التجسيد. ازرع، ابنِ، تحرّك."
        ),
        Insight(
            "«برمودة دق العامودة»", "التجذر والتثبيت",
            "أعطِ رؤيتك شكلاً ملموساً. الالتزام، والنظام، والحدود."
        ),
        Insight(
            "«بشنس يكنس الغيط كنس»", "الحصاد والإتمام",
            "اجمع ثمار التجربة، ثم نظّف الحقل. اترك البقايا."
        ),
        Insight(
            "«بؤونة نقل وتخزين المونة»", "الدمج والحفظ",
            "خزّن الحكمة. حوّل التجارب إلى معرفة وموارد للمستقبل."
        ),
        Insight(
            "«أبيب فيه العنب يطيب»", "النضج",
            "اسمح لما زرعته أن ينضج. لا تستعجل."
        ),
        Insight(
            "«مسرى تجري فيه كل ترعة عسيرة»", "التدفق والتسليم",
            "دع المياه تتحرك، حرّر السيطرة. سامح، أفرغ، وأعد فتح القنوات التي انسدت داخلك."
        ),
        Insight(
            "الأيام المكمّلة للسنة", "العتبة المقدسة",
            "راجع، اشكر، سامح، احتفل. أفرغ نفسك، ولا تتعجل. تجدّد من سكونك."
        )
    )

    private val AKHET = Season("أخيت · الفيضان", "التجدد والامتداد")
    private val PERET = Season("بيرت · الزراعة والنمو", "الفعل والتجذر")
    private val SHEMU = Season("شمو · الحصاد", "النضج والاكتمال")

    fun forCopticMonth(month: Int): Insight = MONTHS[month.coerceIn(0, MONTHS.size - 1)]

    // النسيء عتبة بين دورتين، فبنحسبه مع شمو (آخر السنة)
    fun seasonFor(month: Int): Season = when (month) {
        in 0..3 -> AKHET
        in 4..7 -> PERET
        else -> SHEMU
    }
}
